import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { documentCss } from '../element';
import { CARD_THEME } from '../parts';
import { APPEARANCE_INPUTS, type StripeAppearance } from './appearance';
import { brandCss, brandSeedOf } from './brand';
import { LENGTH_TOKENS, NUMBER_TOKENS, resolveAppearance } from './resolve';
import tokens from './tokens.css?inline';

// the browser pool, and the only pool that can see any of this. a registry step behind its `var()`s
// is resolved at computed-value time by a real engine and painted to sRGB by a real canvas — a
// lightweight DOM hands both back as the strings they were given, so an assertion there would be
// asserting the fixture rather than the ramp. run with `pnpm test:browser`; it is deliberately
// outside `pnpm test` and outside the deploy gate (see vitest.browser.config.ts).

const sheet = new CSSStyleSheet();
sheet.replaceSync(tokens);

/** what the element puts in the document: the seed registrations. */
const documentSheet = new CSSStyleSheet();
documentSheet.replaceSync(documentCss(tokens));

/** the element's brand sheet, regenerated by `seed` below as the element regenerates its own. */
const brandSheet = new CSSStyleSheet();

const RGB = /^rgb\((\d{1,3}), (\d{1,3}), (\d{1,3})\)$/;

let host: HTMLElement;
let card: HTMLElement;
let hostStyle: HTMLStyleElement;

beforeEach(() => {
	// the two trees the element puts its sheets in, and both are load-bearing: the shadow root is
	// where `:host` and the card's theme apply, and the document is the only tree `@property`
	// registrations are collected from.
	document.adoptedStyleSheets = [documentSheet];

	host = document.createElement('div');
	host.id = 'donate-host';
	document.body.appendChild(host);

	brandSheet.replaceSync('');
	const shadow = host.attachShadow({ mode: 'open' });
	shadow.adoptedStyleSheets = [sheet, brandSheet];

	// what the element hands the resolver: a node inside the card, whose root carries the theme.
	card = document.createElement('div');
	card.setAttribute('data-theme', CARD_THEME);
	shadow.appendChild(card);

	hostStyle = document.createElement('style');
	document.head.appendChild(hostStyle);
});

afterEach(() => {
	document.adoptedStyleSheets = [];
	host.remove();
	hostStyle.remove();
});

/** where each token of a kind comes out, once it has crossed that kind's carrier. */
type LandsAt = Record<string, (appearance: StripeAppearance) => string | undefined>;

const LENGTH_LANDS_AT: LandsAt = {
	'--_border': (a) => a.rules['.Input']?.border?.split(' ')[0],
	'--_focus-width': (a) => a.rules['.Input:focus']?.boxShadow?.split(' ')[3],
	'--_r': (a) => a.variables.borderRadius,
	'--_r-in': (a) => a.rules['.AccordionItem']?.borderRadius,
	'--_sp1': (a) => a.variables.spacingUnit,
	'--_sp3': (a) => a.rules['.AccordionItem']?.paddingTop,
	'--_sp4': (a) => a.rules['.AccordionItem']?.paddingLeft,
	'--_sp5': (a) => a.variables.accordionItemSpacing,
	'--_t-sm': (a) => a.rules['.Label']?.fontSize
};

/** the same for the number kind, carrying the weight ./tokens.css states for each token. */
const NUMBER_LANDS_AT: Record<
	string,
	{ readonly is: string; readonly at: (appearance: StripeAppearance) => string | undefined }
> = {
	'--_w-bold': { is: '600', at: (a) => a.rules['.Label']?.fontWeight }
};

/** what a host page wrote on the element, and the brand sheet the element writes from it. */
function seed(declarations: string): void {
	hostStyle.textContent = `#donate-host { ${declarations} }`;
	brandSheet.replaceSync(brandCss(brandSeedOf(host)));
}

describe('what the provider is handed', () => {
	it('fills every variable and every rule the map declares', () => {
		const appearance = resolveAppearance(card);

		expect(Object.keys(appearance.variables).sort()).toEqual([
			'accordionItemLabelFontSize',
			'accordionItemSpacing',
			'borderRadius',
			'colorBackground',
			'colorDanger',
			'colorPrimary',
			'colorText',
			'colorTextPlaceholder',
			'colorTextSecondary',
			'fontFamily',
			'fontSizeBase',
			'spacingUnit'
		]);
		expect(Object.keys(appearance.rules).sort()).toEqual([
			'.AccordionItem',
			'.AccordionItem--selected',
			'.AccordionItem--selected:focus-visible',
			'.AccordionItem--selected:hover',
			'.AccordionItem:focus-visible',
			'.AccordionItem:hover',
			'.Input',
			'.Input--invalid',
			'.Input--invalid:focus',
			'.Input--invalid:hover',
			'.Input:focus',
			'.Input:hover',
			'.Label'
		]);
	});

	// a token added to ./appearance.ts's input list and not classified in ./resolve.ts would
	// otherwise arrive as an unresolved string rather than as a failure.
	it('resolves every input the map asks for', () => {
		const appearance = resolveAppearance(card);
		const sent = JSON.stringify(appearance);

		expect(APPEARANCE_INPUTS.length).toBe(22);
		expect(sent).not.toContain('var(');
		expect(sent).not.toContain('oklch');
	});

	// the provider parses these strings inside its own frame and derives further shades from
	// them. a notation it cannot read is not a wrong color, it is no color at all.
	it('states colors in sRGB rather than in the space they are authored in', () => {
		const appearance = resolveAppearance(card);

		expect(appearance.variables.colorPrimary).toMatch(RGB);
		expect(appearance.variables.colorBackground).toMatch(RGB);
		expect(appearance.variables.colorText).toMatch(RGB);
		expect(appearance.variables.colorDanger).toMatch(RGB);
	});

	it('carries the host’s own seed into the provider’s fields', () => {
		seed('--donate-primary: oklch(0.45 0.15 25);');
		const warm = resolveAppearance(card).variables.colorPrimary ?? '';
		seed('--donate-primary: oklch(0.45 0.15 250);');
		const cool = resolveAppearance(card).variables.colorPrimary ?? '';

		const [, warmRed = '0', , warmBlue = '0'] = RGB.exec(warm) ?? [];
		const [, coolRed = '0', , coolBlue = '0'] = RGB.exec(cool) ?? [];

		expect(Number(warmRed)).toBeGreaterThan(Number(coolRed));
		expect(Number(coolBlue)).toBeGreaterThan(Number(warmBlue));
	});

	// the preset switches on the card rather than on the host, so this is the reading that shows the
	// probe is standing where it lands: the provider's fields take the card's corner.
	it('carries the host’s corner into the provider’s fields', () => {
		seed('--donate-corner: round;');
		const round = resolveAppearance(card);
		seed('--donate-corner: square;');
		const square = resolveAppearance(card);

		expect(round.variables.borderRadius).toBe('24px');
		expect(square.variables.borderRadius).toBe('0px');
		// and a rail takes the preset's control corner, the one every box on the card is drawn at.
		expect(round.rules['.AccordionItem']?.borderRadius).toBe('12px');
		expect(square.rules['.AccordionItem']?.borderRadius).toBe('0px');
	});

	// the split, proven off a real cascade rather than off a table: the fill inside the provider's
	// frame is the seed's step 9 and the ring is the registry's ring, step 8 of the same scale, two
	// colours off one seed. only this pool can see it — `--_p` and `--_focus-ring` are unregistered
	// custom properties, so a lightweight DOM hands back the `var()` and never a colour.
	it('sends the seed’s step 9 to the fills and its ring to the ring', () => {
		seed('--donate-primary: oklch(0.45 0.15 25);');
		const warm = resolveAppearance(card);
		seed('--donate-primary: oklch(0.45 0.15 250);');
		const cool = resolveAppearance(card);

		// both move with the seed, because both are steps of its scale.
		expect(cool.variables.colorPrimary).not.toBe(warm.variables.colorPrimary);
		expect(cool.rules['.Input:focus']?.boxShadow).not.toBe(warm.rules['.Input:focus']?.boxShadow);
		// and the ring is not the fill under another name: a token quietly repointed at `--_p` would
		// pass both lines above and fail here.
		expect(warm.rules['.Input:focus']?.boxShadow).not.toBe(
			`0 0 0 1px ${warm.variables.colorPrimary}`
		);
	});

	// inside the provider's frame there is no clamped root for an `em` to resolve against, so
	// every length crosses the boundary already stated in absolute units.
	it('states the lengths in units that survive the frame boundary', () => {
		const appearance = resolveAppearance(card);

		// the row's size and not the card's root: the fields stand inside a payment row, drawn at
		// `--_t-sm` (`.name` in ./rows.css), and the root the provider is given is what sizes them.
		expect(appearance.variables.fontSizeBase).toBe('14px');
		expect(appearance.variables.spacingUnit).toBe('4px');
		expect(appearance.variables.borderRadius).toBe('12px');
		// the rail's pads, the gap between two rails and the rail's corner: spacing steps are `em` on
		// this side of the frame and converted against the root the form resolved to before they
		// cross.
		expect(appearance.rules['.AccordionItem']?.paddingLeft).toBe('16px');
		expect(appearance.rules['.AccordionItem']?.paddingTop).toBe('12px');
		expect(appearance.variables.accordionItemSpacing).toBe('20px');
		expect(appearance.rules['.AccordionItem']?.borderRadius).toBe('6px');
		expect(appearance.rules['.Label']?.fontSize).toBe('14px');
		// the frame is assembled from two tokens rather than from a literal, so both halves have to
		// have crossed: a weight the engine resolved and a colour the canvas painted.
		expect(appearance.rules['.Input']?.border).toMatch(/^1px solid rgb\(\d+, \d+, \d+\)$/);
		expect(appearance.rules['.Input:focus']?.boxShadow).toMatch(/^0 0 0 1px rgb\(\d+, \d+, \d+\)$/);
	});

	// the carrier a length is read through is the whole of what makes an unresolved one visible,
	// and a property that carries the kind but does not hand the value back would fail silently
	// the other way — every length absent from an object nothing else complains about. the table
	// is held to the partition, so a token added to `LENGTH_TOKENS` and not asserted here is a
	// failure rather than an untested carrier.
	it('round-trips every length in the partition through its carrier', () => {
		const appearance = resolveAppearance(card);

		expect(Object.keys(LENGTH_LANDS_AT).sort()).toEqual([...LENGTH_TOKENS].sort());
		for (const [token, lands] of Object.entries(LENGTH_LANDS_AT)) {
			expect(lands(appearance), token).toMatch(/^\d+(?:\.\d+)?px$/);
		}
	});

	// the same for the number kind, and its carrier bounds what may join the partition: a number
	// outside [1, 1000] is not clamped by `font-weight`, it inherits the sentinel and is dropped.
	// a token that is not a weight therefore goes missing here rather than arriving wrong, and
	// only across the part of its range that a weight does not cover.
	it('round-trips every number in the partition through its carrier', () => {
		const appearance = resolveAppearance(card);

		expect(Object.keys(NUMBER_LANDS_AT).sort()).toEqual([...NUMBER_TOKENS].sort());
		for (const [token, lands] of Object.entries(NUMBER_LANDS_AT)) {
			expect(lands.at(appearance), token).toBe(lands.is);
		}
	});

	it('leaves nothing of its own in the card it measured', () => {
		resolveAppearance(card);

		expect(card.childElementCount).toBe(0);
	});
});

describe('a cascade the registration did not reach', () => {
	// `@property` registrations are collected from the document tree only, so a page that never got
	// the document sheet leaves the seed unregistered. no colour on the card is derived from the seed
	// in a stylesheet any more — the registry theme is literals, and a seed reaches the card only
	// through the brand sheet the element writes — so what the provider is handed is the registry's
	// default theme, whole. this is the assertion that would catch a colour quietly re-derived from
	// the seed in ./tokens.css: it would go absent here.
	it('sends the registry’s default theme, every colour resolved', () => {
		document.adoptedStyleSheets = [];
		seed('');

		const appearance = resolveAppearance(card);

		expect(appearance.variables.colorPrimary).toBe('rgb(30, 109, 171)');
		expect(appearance.variables.colorBackground).toBe('rgb(251, 252, 254)');
		expect(appearance.variables.colorText).toEqual(expect.stringMatching(RGB));
		expect(appearance.variables.colorDanger).toEqual(expect.stringMatching(RGB));
		expect(appearance.variables.borderRadius).toBe('12px');
	});
});

describe('a cascade the sheet never reached at all', () => {
	// the sheet adopted into neither tree: nothing under `:host` and no registry theme was ever
	// declared, so every step is a `var()` naming nothing. sent as what a carrier hands back on its own, this is a card
	// with square corners, no spacing between its rails, and field labels — `MM / YY`, `CVC`, the
	// only thing naming those fields — set at `0px` and at whatever weight the host page's own
	// text happens to be.
	it('sends nothing it could not resolve rather than a page of defaults', () => {
		document.adoptedStyleSheets = [];
		if (host.shadowRoot !== null) host.shadowRoot.adoptedStyleSheets = [];

		const appearance = resolveAppearance(card);

		expect(appearance.variables).not.toHaveProperty('borderRadius');
		expect(appearance.variables).not.toHaveProperty('spacingUnit');
		expect(appearance.variables).not.toHaveProperty('accordionItemSpacing');
		// not one rule read from a token survives, and the whole object is the assertion: a rule
		// left holding a single declaration is a surface this form claims to have drawn on a page
		// where it resolved nothing at all. two rules are the exception, because neither reads a
		// token. the rail's refused lift is a keyword rather than a read — ./appearance.ts sends it
		// whatever resolved, and the rail's edge, corner, face and pads are dropped with every other one.
		// and the typed field's size is `[part~='field']`'s `max(16px, 1em)` in ./parts.css: a literal
		// floor over the card's computed `font-size`, a standard property the browser resolves on any
		// page, so it is sent here too, and at the floor.
		expect(appearance.rules).toEqual({
			'.Input': { fontSize: '16px' },
			'.AccordionItem': { boxShadow: 'none' }
		});
	});
});
