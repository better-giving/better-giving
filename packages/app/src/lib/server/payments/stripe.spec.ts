// the adapter, exercised through a recording HTTP client rather than a stubbed SDK.
//
// the seam is one level lower than it looks like it should be, deliberately. a fake
// `stripe.paymentIntents` object would prove that this module calls a method — which is the one
// thing that was never in doubt — while every mistake worth catching lives in what actually goes
// on the wire: an amount in the wrong unit, a currency in the wrong case, a rail the donor was not
// quoted on, an idempotency key that never left. handing the real SDK a client that records
// instead of dialling means the request under assertion is the request Stripe would receive,
// encoded by Stripe's own encoder.
//
// what this pool cannot see is whether the client production builds works at all, because every
// case here injects one. ./stripe.workers.spec.ts is where that is covered, inside workerd.
//
// nothing here imports `stripe`. that is the rule ./sole-importer.spec.ts enforces over the tree,
// and it costs this file nothing: the stub is structural, and the one place a spec would
// ordinarily reach for the SDK — minting a valid webhook signature — is a short HMAC below, which
// is a better test anyway. a signature generated by the same library that verifies it proves the
// two agree, not that either matches what Stripe sends.

/** one request the adapter made, as the assertions need to read it. */
type Recorded = {
	readonly path: string;
	readonly method: string;
	readonly body: string;
	readonly headers: Record<string, string | number | string[]>;
};

/**
 * an HTTP client that answers from a script and remembers what it was asked.
 *
 * responses are consumed in order. running out is an error rather than a default, because a test
 * that made one more call than it scripted is a test whose subject did something it was not
 * asked to — and a permissive fallback would hide exactly that.
 */
function recording(responses: readonly { status: number; json: unknown }[]) {
	const remaining = [...responses];
	const calls: Recorded[] = [];
	const httpClient = {
		getClientName: () => 'recording',
		async makeRequest(
			_host: string,
			_port: string,
			path: string,
			method: string,
			headers: Record<string, string | number | string[]>,
			requestData: string
		) {
			calls.push({ path, method, body: requestData, headers });
			const next = remaining.shift();
			if (!next) throw new Error(`unscripted request: ${method} ${path}`);
			return {
				getStatusCode: () => next.status,
				getHeaders: () => ({}),
				// an object rather than null: the SDK hangs `requestId` off whatever this returns
				// and exposes it as `lastResponse`, so a null here is a TypeError inside the SDK
				// before any assertion is reached.
				getRawResponse: () => ({}),
				// required by the interface and never reached: nothing this adapter calls streams a
				// response. omitted, the stub stops satisfying `HttpClientInterface` and every case
				// below fails to type-check rather than to run.
				toStream: () => null,
				// a fresh copy per answer. the SDK seals a non-writable `lastResponse` onto whatever
				// this returns, so handing back a shared literal twice throws on the second call
				// instead of answering it.
				toJSON: async () => structuredClone(next.json)
			};
		}
	};
	return { httpClient, calls };
}

/**
 * the form-encoded body of a recorded request, parsed.
 *
 * parsed rather than substring-matched, and that is not tidiness. `toContain('amount=12345')` is
 * satisfied by `amount=123450`, so the assertion whose whole purpose is "no conversion happened"
 * catches a divide by ten and misses a multiply by ten. on the path that decides what a donor is
 * charged, that asymmetry is the wrong way round.
 */
function fields(call: Recorded | undefined): URLSearchParams {
	return new URLSearchParams(call?.body ?? '');
}

