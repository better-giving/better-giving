describe('error mapping', () => {
	/**
	 * the processor's error types are sorted into ours, and they are not one thing.
	 *
	 * what a caller does about each is different, which is the whole reason the reasons exist:
	 * an operator fixes a rejected key, nobody fixes a 500 by retyping anything, a rate limit is
	 * worth the same call again, and a malformed request is a bug in this app that will fail
	 * identically forever. flattened to one code they would all read as "payments are down".
	 */
	it.each([
		[400, { type: 'invalid_request_error', message: 'No such price' }, 'invalid_request'],
		[401, { type: 'invalid_request_error', message: 'Invalid API Key' }, 'not_configured'],
		[403, { type: 'invalid_request_error', message: 'not permitted' }, 'not_configured'],
		[429, { type: 'rate_limit_error', message: 'Too many requests' }, 'rate_limited'],
		[500, { type: 'api_error', message: 'Something went wrong' }, 'provider_error']
	])('maps a %s answer to %s', async (status, error, reason) => {
		const { httpClient } = recording([{ status, json: { error } }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		expect(result.ok === false && result.reason).toBe(reason);
	});

	/**
	 * a reused idempotency key is a permanent 400 and must never read as retryable.
	 *
	 * `StripeIdempotencyError` extends the base error class directly rather than the
	 * invalid-request one, so it reaches the general arm unless it is named ahead of it — and the
	 * general arm is `provider_error`, which `isRetryable` in ./provider.ts calls worth repeating.
	 * a key reused against different parameters answers identically every time, so read that way
	 * the webhook holds a delivery open for three days against a request that cannot ever succeed.
	 */
	it('maps a reused idempotency key to a terminal invalid_request', async () => {
		const { httpClient } = recording([
			{
				status: 400,
				json: {
					error: {
						type: 'idempotency_error',
						message: 'Keys for idempotent requests can only be used with the same parameters.'
					}
				}
			}
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		expect(result.ok === false && result.reason).toBe('invalid_request');
		expect(result.ok === false && result.detail).toContain('idempotencyKey');
	});

	/**
	 * a card error out of a call that charges nothing is our bug, not a donor's card.
	 *
	 * it shares `StripeIdempotencyError`'s shape — a direct subclass of the base error — so it has
	 * the same fall-through hazard. nothing this adapter calls confirms a payment, so one arriving
	 * at all means the request was wrong; a real decline reaches this app as a `Settlement` whose
	 * status is `failed`, never as a failure.
	 */
	it('maps a card error to a terminal invalid_request', async () => {
		const { httpClient } = recording([
			{
				status: 402,
				json: {
					error: { type: 'card_error', code: 'card_declined', message: 'Your card was declined.' }
				}
			}
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		expect(result.ok === false && result.reason).toBe('invalid_request');
	});

	/**
	 * an answer that never came back is `unreachable`, and it is the one failure that says nothing
	 * about whether the intent exists.
	 *
	 * that is exactly what the caller's idempotency key answers — the same call made again
	 * resolves to the intent the lost request may have created — so the reason's job is only to
	 * say "this is worth repeating", not to guess.
	 */
	it('maps a connection that never answered to unreachable', async () => {
		const httpClient = {
			getClientName: () => 'exploding',
			makeRequest: () => Promise.reject(new Error('socket hang up'))
		};

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		expect(result.ok === false && result.reason).toBe('unreachable');
	});

	/**
	 * the processor's own sentence survives into the detail.
	 *
	 * CLAUDE.md: a 4xx body names the offending value and where to fix it, and these bodies are
	 * read by agents. a reason code alone says which screen; the processor's message is the only
	 * thing that says which field.
	 */
	it('carries the processor’s message into the detail', async () => {
		const { httpClient } = recording([
			{
				status: 400,
				json: { error: { type: 'invalid_request_error', message: 'Amount must be at least $0.50' } }
			}
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent({
			...REQUEST,
			amountMinor: 10
		});

		expect(result.ok === false && result.detail).toContain('Amount must be at least $0.50');
	});

	/**
	 * a key-shaped token inside the processor's own sentence does not survive into ours.
	 *
	 * this is the live vector and it is not hypothetical: a rejected key is described by quoting a
	 * masked copy of the value that was sent, and that sentence lands in a detail that reaches a
	 * 4xx body and /admin. masked is not absent — the prefix names the mode and the account, and
	 * ../../redact.ts states the echo policy with no exception for text somebody else wrote. the
	 * fixture carries a real key shape rather than the words "Invalid API Key", because a fixture
	 * with no token in it has nothing to fail against.
	 */
	it('strips a key-shaped token out of the processor’s message', async () => {
		const { httpClient } = recording([
			{
				status: 401,
				json: {
					error: {
						type: 'invalid_request_error',
						message: 'Invalid API Key provided: sk_test_51H2***************kQ0y'
					}
				}
			}
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		const detail = result.ok === false ? result.detail : '';
		expect(detail).not.toContain('sk_test_51H2');
		expect(detail).toContain('[redacted credential]');
	});

	/**
	 * a sentence written by somebody else cannot decide how long ours is.
	 *
	 * the processor's error strings are not a bounded vocabulary — a parse failure embeds a slice
	 * of the body it choked on, and that body is whatever was posted to a public endpoint — so a
	 * concatenation with no ceiling is a refusal whose length is chosen by the sender.
	 */
	it('bounds how much of the processor’s message it repeats', async () => {
		const { httpClient } = recording([
			{ status: 400, json: { error: { type: 'invalid_request_error', message: 'x'.repeat(5000) } } }
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).createIntent(REQUEST);

		const detail = result.ok === false ? result.detail : '';
		expect(detail.length).toBeLessThan(600);
		expect(detail).toContain('…');
	});

	/**
	 * a refused key never quotes the key this deployment holds.
	 *
	 * the value in `STRIPE_SECRET_KEY` is the one credential this module carries, and a 401 is
	 * precisely the moment somebody is tempted to echo it back so the operator can see what was
	 * wrong with it. the finding is the slot, never the secret — the echo policy in
	 * `$lib/redact.ts`, which has no exception for text a processor wrote.
	 */
	it('names the variable and never the configured key when a key is rejected', async () => {
		const { httpClient } = recording([
			{
				status: 401,
				json: { error: { type: 'invalid_request_error', message: 'Invalid API Key' } }
			}
		]);

		const result = await createStripeProvider(
			{ secretKey: 'sk_test_supersecretvalue', webhookSecret: 'whsec_x' },
			{ httpClient }
		).createIntent(REQUEST);

		const detail = result.ok === false ? result.detail : '';
		expect(detail).toContain('STRIPE_SECRET_KEY');
		expect(detail).not.toContain('supersecretvalue');
	});
});

/**
 * a `stripe-signature` header, computed here rather than asked for.
 *
 * the scheme is published: `t=<unix seconds>,v1=<hex HMAC-SHA256 of "<t>.<body>" under the
 * signing secret>` — https://docs.stripe.com/webhooks#verify-manually. computing it in the test
 * is what makes the assertion mean something: a header generated by the same library that
 * verifies it proves only that the library agrees with itself, and would keep passing if both
 * halves drifted away from what Stripe actually sends.
 */
async function sign(body: string, secret: string, atSeconds = Math.floor(Date.now() / 1000)) {
	const encoder = new TextEncoder();
	const key = await crypto.subtle.importKey(
		'raw',
		encoder.encode(secret),
		{ name: 'HMAC', hash: 'SHA-256' },
		false,
		['sign']
	);
	const mac = await crypto.subtle.sign('HMAC', key, encoder.encode(`${atSeconds}.${body}`));
	const hex = [...new Uint8Array(mac)].map((b) => b.toString(16).padStart(2, '0')).join('');
	return `t=${atSeconds},v1=${hex}`;
}

/** a delivery body, as it arrives: one string, never re-serialised. */
function eventBody(type: string, object: unknown = { id: 'pi_1', object: 'payment_intent' }) {
	return JSON.stringify({
		id: 'evt_1',
		object: 'event',
		type,
		created: 1_770_000_000,
		data: { object }
	});
}

describe('verifyEvent', () => {
	/** the ordinary case: a real signature, and the facts the handler needs out of it. */
	it('accepts a correctly signed delivery and reports what it is about', async () => {
		const body = eventBody('payment_intent.succeeded');
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result).toEqual({
			ok: true,
			value: {
				id: 'evt_1',
				kind: 'settlement',
				type: 'payment_intent.succeeded',
				providerTxnId: 'pi_1',
				occurredAt: new Date(1_770_000_000_000)
			}
		});
	});

	/**
	 * a body that changed after it was signed is refused.
	 *
	 * this is the endpoint's entire defence. it is public and it grants donation records, so an
	 * unverified body is a way to write yourself a receipt — and the tampering that matters is
	 * exactly this shape: a real delivery's signature over an amount somebody edited.
	 */
	it('refuses a delivery whose body was altered after signing', async () => {
		const signature = await sign(eventBody('payment_intent.succeeded'), CREDENTIALS.webhookSecret);
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body: eventBody('payment_intent.succeeded', { id: 'pi_ATTACKER', object: 'payment_intent' }),
			signature
		});

		expect(result.ok === false && result.reason).toBe('bad_signature');
	});

	/** signed under someone else's secret, which is a signature and not this endpoint's. */
	it('refuses a delivery signed with a different secret', async () => {
		const body = eventBody('payment_intent.succeeded');
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, 'whsec_someoneelses')
		});

		expect(result.ok === false && result.reason).toBe('bad_signature');
	});

	/** no header at all is the shape a hand-rolled POST takes, and it is refused like any other. */
	it('refuses a delivery with no signature header', async () => {
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body: eventBody('payment_intent.succeeded'),
			signature: null
		});

		expect(result.ok === false && result.reason).toBe('bad_signature');
	});

	/**
	 * a signature too old to be this delivery is refused.
	 *
	 * without the timestamp in the signed material, a delivery captured once could be posted back
	 * forever and would verify every time. the tolerance is what makes a replay expire.
	 */
	it('refuses a delivery whose signature is outside the tolerance window', async () => {
		const body = eventBody('payment_intent.succeeded');
		const hoursAgo = Math.floor(Date.now() / 1000) - 3600;
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret, hoursAgo)
		});

		expect(result.ok === false && result.reason).toBe('bad_signature');
	});

	/**
	 * a body that verified and then could not be read is not a signature problem.
	 *
	 * the two failures leave through the same call and lead to opposite actions. reported as
	 * `bad_signature`, this one sends an operator to rotate a secret that was never wrong — while
	 * the deliveries keep arriving and keep failing, because the secret was never what was wrong.
	 */
	it('separates a body that will not parse from a signature that did not verify', async () => {
		const body = 'not json at all';
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result.ok === false && result.reason).toBe('provider_error');
	});

	/**
	 * an unparseable body cannot leak itself through the error that describes it.
	 *
	 * V8 puts a slice of the offending input into a `SyntaxError`'s message, and the input here is
	 * whatever was posted to a public endpoint — so the sanitiser has to cover this path and not
	 * only the ones where the processor wrote the sentence.
	 */
	it('does not repeat a key-shaped token out of an unparseable body', async () => {
		const body = 'sk_live_51abcdefghijklmnopqrstuvwx not json';
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result.ok === false && result.detail).not.toContain('sk_live_51abcdefghijklmnop');
	});

	/**
	 * an endpoint subscribed to more than this app handles answers, logs and does nothing.
	 *
	 * subscriptions are configured in a dashboard, so the set that arrives is not the set this
	 * code knows. an unrecognised type is a named outcome rather than a silent fall-through,
	 * which is what lets the handler say so instead of merely returning 200.
	 *
	 * a refund is the honest example rather than an invented type: it is a real delivery this
	 * account can send, and `SETTLEMENT_EVENT_TYPES` in ./stripe.ts says in as many words why it is
	 * not handled here.
	 */
	it('reports an event this app handles nothing for as ignored', async () => {
		const body = eventBody('charge.refunded', { id: 'ch_1', object: 'charge' });
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result).toEqual({
			ok: true,
			value: {
				id: 'evt_1',
				kind: 'ignored',
				type: 'charge.refunded',
				occurredAt: new Date(1_770_000_000_000)
			}
		});
	});

	/**
	 * a delivery about a repeating gift is its own kind, and it names something that is not a
	 * transaction.
	 *
	 * this is the whole of why widening `SETTLEMENT_EVENT_TYPES` was not the change: the object on a
	 * delivery about a commitment is a subscription or an invoice, so its id is a `sub_…` or an
	 * `in_…`. reported as a settlement it would be handed to `readSettlement`, which retrieves a
	 * payment intent — a `not_found` against an id that exists, for every collection a donor ever
	 * makes.
	 */
	it('reports a delivery about a repeating gift as its own kind', async () => {
		const body = eventBody('customer.subscription.updated', {
			id: 'sub_1',
			object: 'subscription'
		});
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result).toEqual({
			ok: true,
			value: {
				id: 'evt_1',
				kind: 'recurring',
				type: 'customer.subscription.updated',
				providerNoticeId: 'sub_1',
				occurredAt: new Date(1_770_000_000_000)
			}
		});
	});

	/**
	 * every recurring event names the object the read arm has to fetch.
	 *
	 * the mirror of the settlement case below, and it has to hold across the whole subscribed set
	 * for the same reason: what `readRecurringGift` retrieves is decided by the type, so a member
	 * that arrived with nothing readable on it would be a collection dropped in silence.
	 */
	it.each(RECURRING_EVENT_TYPES)('reads the object id out of %s', async (type) => {
		const object = type.startsWith('invoice.')
			? { id: 'in_1', object: 'invoice' }
			: { id: 'sub_1', object: 'subscription' };
		const body = eventBody(type, object);
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result.ok === true && result.value.kind).toBe('recurring');
		expect(
			result.ok === true && result.value.kind === 'recurring' && result.value.providerNoticeId
		).toBe(object.id);
	});

	/**
	 * every settlement event carries the transaction it is about.
	 *
	 * `kind` collapses them on purpose — the handler re-reads the transaction either way, because
	 * deliveries have no ordering guarantee — so what has to hold across the whole subscribed set
	 * is that each one names something to re-read.
	 */
	it.each(SETTLEMENT_EVENT_TYPES)('reads the transaction id out of %s', async (type) => {
		const body = eventBody(type);
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result.ok === true && result.value.kind).toBe('settlement');
		expect(
			result.ok === true && result.value.kind === 'settlement' && result.value.providerTxnId
		).toBe('pi_1');
	});

	/**
	 * a subscribed event whose transaction cannot be read is a fault, not an ignore.
	 *
	 * an event is serialised in the API version the account was on when it happened, so a replay
	 * of an old delivery can carry a shape this app does not recognise. reported as `ignored` it
	 * would be a settlement dropped in silence with a 200 over the top, which is the failure that
	 * loses a gift rather than duplicating one.
	 */
	it('refuses a settlement event with no readable transaction id', async () => {
		const body = eventBody('payment_intent.succeeded', { object: 'payment_intent' });
		const { httpClient } = recording([]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).verifyEvent({
			body,
			signature: await sign(body, CREDENTIALS.webhookSecret)
		});

		expect(result.ok === false && result.reason).toBe('provider_error');
	});
});

/** a settled intent, with the charge and balance transaction the adapter asks to have expanded. */
function settled(overrides: Record<string, unknown> = {}) {
	return {
		id: 'pi_1',
		object: 'payment_intent',
		status: 'succeeded',
		amount: 10_329,
		currency: 'usd',
		created: 1_770_000_000,
		metadata: { donation_id: '01932f7c' },
		latest_charge: {
			id: 'ch_1',
			object: 'charge',
			amount: 10_329,
			created: 1_770_000_060,
			payment_method_details: { type: 'card' },
			balance_transaction: {
				id: 'txn_1',
				object: 'balance_transaction',
				currency: 'usd',
				fee: 330,
				// null on a transaction that converted nothing, which is what Stripe sends on a gift
				// charged in the account's own currency. widened because the cases that convert set it.
				exchange_rate: null as number | null,
				created: 1_770_000_120
			}
		},
		...overrides
	};
}

/**
 * a gift that settled a moment ago and whose fee Stripe has not computed yet.
 *
 * the charge is there and its balance transaction is not, which is the shape the webhook arrives
 * about. the times are read off the clock rather than fixed, because the adapter measures the
 * charge's age to decide whether the figure is still worth waiting for — a fixed date would be
 * hours old on the first run of the suite and every case here would take the give-up arm.
 */
function unpriced(secondsOld = 0, overrides: Record<string, unknown> = {}) {
	const when = Math.floor(Date.now() / 1000) - secondsOld;
	return settled({
		created: when,
		latest_charge: {
			id: 'ch_1',
			object: 'charge',
			amount: 10_329,
			created: when,
			payment_method_details: { type: 'card' },
			balance_transaction: null
		},
		...overrides
	});
}

describe('readSettlement', () => {
	/**
	 * the fee is asked for in the same round trip.
	 *
	 * it is two levels down and neither level is expanded by default, so without this the charge
	 * is an id string and the fee is not in the answer at all. asserted on the request because the
	 * failure without it is not an error — it is a settlement that reads clean with `feeMinor:
	 * null` forever, and a ledger that never records what the processor took.
	 */
	it('asks for the charge and its balance transaction', async () => {
		const { httpClient, calls } = recording([{ status: 200, json: settled() }]);

		await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		// a retrieve is a GET, so the expand rides in the query string rather than a body.
		expect(decodeURIComponent(calls[0]?.path ?? '')).toBe(
			'/v1/payment_intents/pi_1?expand[0]=latest_charge.balance_transaction'
		);
	});

	/**
	 * the fee is the processor's own figure, and the currency comes back uppercase.
	 *
	 * two boundary conversions in one answer. the fee has to be Stripe's number rather than the
	 * one this app quoted, because the ledger's fee entry is reconciled against a bank statement
	 * while the donor-facing figure stays what they agreed to — the two are allowed to differ and
	 * the books only balance against the first. and the currency is uppercased here because Stripe
	 * reports `usd` while `post()` refuses anything but `/^[A-Z]{3}$/` (../ledger/posting.ts),
	 * where a lowercase value would satisfy a length-3 check and split every total in the books.
	 */
	it('reports the processor’s own fee and an uppercase currency', async () => {
		const { httpClient } = recording([{ status: 200, json: settled() }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.feeMinor).toBe(330);
		expect(result.ok === true && result.value.currency).toBe('USD');
	});

	/**
	 * the rail that settled comes from the charge, not from what the donor picked.
	 *
	 * those are two different facts and the fee was priced off the first, so recording the donor's
	 * pre-selection under the name of the settled rail is what would make a divergence between
	 * them permanently invisible. mapped into the `payment.method` column's vocabulary
	 * (../db/schema.ts), which is not the vocabulary the wire uses.
	 */
	it.each([
		['card', 'card'],
		['us_bank_account', 'ach']
	])('reads a %s charge as the %s rail', async (reported, expected) => {
		const intent = settled();
		intent.latest_charge.payment_method_details = { type: reported };
		const { httpClient } = recording([{ status: 200, json: intent }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.method).toBe(expected);
	});

	/**
	 * a rail this schema does not model reads null rather than being coerced into one that is.
	 *
	 * an account can be configured for methods a donation form never shows, so a charge can
	 * legitimately settle on one. a value invented for that case would be a `payment` row
	 * asserting a rail nobody used, which is worse than an absence a reader can see.
	 */
	it('reports a rail this schema does not model as no rail at all', async () => {
		const intent = settled();
		intent.latest_charge.payment_method_details = { type: 'cashapp' };
		const { httpClient } = recording([{ status: 200, json: intent }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.method).toBeNull();
	});

	/**
	 * the metadata written onto the intent comes back out.
	 *
	 * this is what makes writing it worth anything. a delivery can reach the webhook before the
	 * row that caused it is readable, so a handler whose only route back to its gift is a lookup
	 * by transaction id in its own database loses exactly the race the metadata was written for.
	 */
	it('returns the metadata the intent was created with', async () => {
		const { httpClient } = recording([{ status: 200, json: settled() }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.metadata).toEqual({ donation_id: '01932f7c' });
	});

	/**
	 * unix seconds become unix milliseconds.
	 *
	 * a seconds value read as milliseconds is January 1970, which is a real accounting period and
	 * an entry that lands in it silently. the read runs the opposite way from the one in
	 * `ConfirmOutcome`'s microdeposit deadline (packages/form/src/ports.ts) and has the same hazard.
	 */
	it('converts the settlement time from seconds to milliseconds', async () => {
		const { httpClient } = recording([{ status: 200, json: settled() }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.occurredAt).toEqual(new Date(1_770_000_120_000));
	});

	/**
	 * the processor's seven intent states become this schema's four.
	 *
	 * `requires_payment_method` is the pair worth the table. it is where an intent sits both
	 * before anyone has tried to pay and after a rail refused, and `last_payment_error` is the
	 * only thing that tells those apart — read as one state, every decline would be recorded as a
	 * gift still on its way and `donation`'s `failed` state would have no substrate.
	 */
	it.each([
		['succeeded', {}, 'succeeded'],
		['processing', {}, 'pending'],
		['requires_action', {}, 'pending'],
		['requires_confirmation', {}, 'pending'],
		['requires_capture', {}, 'pending'],
		['requires_payment_method', {}, 'pending'],
		[
			'requires_payment_method',
			{ last_payment_error: { code: 'card_declined', message: 'Your card was declined.' } },
			'failed'
		],
		['canceled', {}, 'cancelled']
	])('reads %s as %s', async (status, extra, expected) => {
		const { httpClient } = recording([
			{ status: 200, json: settled({ status, latest_charge: null, ...extra }) }
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.status).toBe(expected);
	});

	/**
	 * no balance transaction is no fee, and that is the ordinary case rather than an error.
	 *
	 * an intent still in flight has nothing settled behind it. null rather than zero, because zero
	 * is a real fee — some rails have one — and a ledger entry posting a fee of zero is a claim
	 * that the processor took nothing.
	 */
	it('reports no fee for an intent with nothing settled behind it', async () => {
		const { httpClient } = recording([
			{ status: 200, json: settled({ status: 'processing', latest_charge: null }) }
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.feeMinor).toBeNull();
		expect(result.ok === true && result.value.status).toBe('pending');
	});

	/**
	 * a fee that settled in another currency is carried across at the rate Stripe used.
	 *
	 * the balance transaction is in the account's settlement currency, which need not be the
	 * currency the donor was charged in, and an entry group holds exactly one currency
	 * (../ledger/posting.ts) — so the fee has to arrive in the gift's currency or not at all. this
	 * is the case most likely to have been mispriced, because a converted gift is exactly where the
	 * processor's real fee exceeds the rule ./fees.ts quotes from.
	 *
	 * the numbers are the direction, and that is the whole point of asserting them. the rate runs
	 * from the charged currency to the settlement currency, so a 66-cent USD fee on a gift charged
	 * in EUR at 1.234 is 66 / 1.234 = 53 EUR cents. applied the other way it reads 81, which is a
	 * plausible figure nothing downstream disagrees with.
	 */
	it('converts a fee that settled in another currency at Stripe’s own rate', async () => {
		const intent = settled({ currency: 'eur' });
		intent.latest_charge.balance_transaction.currency = 'usd';
		intent.latest_charge.balance_transaction.fee = 66;
		intent.latest_charge.balance_transaction.exchange_rate = 1.234;
		const { httpClient } = recording([{ status: 200, json: intent }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.feeMinor).toBe(53);
		expect(result.ok === true && result.value.currency).toBe('EUR');
	});

	/**
	 * a cross-currency fee Stripe stated no rate for is no figure at all.
	 *
	 * `exchange_rate` is null on a transaction that converted nothing, so a fee in another currency
	 * without one is a conversion this app cannot do. null rather than the unconverted figure, which
	 * would balance arithmetically and be wrong by the rate with nothing in the schema able to see
	 * it, and rather than a zero, which claims the processor took nothing. ../donations/settle.ts
	 * tells an operator either way.
	 */
	it('reports no fee when a fee in another currency carries no rate', async () => {
		const intent = settled({ currency: 'eur' });
		intent.latest_charge.balance_transaction.currency = 'usd';
		intent.latest_charge.balance_transaction.exchange_rate = null;
		const { httpClient } = recording([{ status: 200, json: intent }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.feeMinor).toBeNull();
		expect(result.ok === true && result.value.currency).toBe('EUR');
	});

	/**
	 * a fee Stripe has not computed yet is asked for again rather than read as no fee at all.
	 *
	 * `capture_method: automatic_async` has been the default since API version `2024-04-10`, and
	 * under it the balance transaction is documented as possibly absent at the moment the payment
	 * succeeds (https://docs.stripe.com/payments/payment-intents/asynchronous-capture). read once,
	 * this is the race every card gift runs: the charge posts at face value, the fee posts never,
	 * and `1020 Undeposited Funds` is overstated with a clean 200 over the top.
	 */
	it('asks again for a fee Stripe has not computed yet, and reports it when it appears', async () => {
		const { httpClient, calls } = recording([
			{ status: 200, json: unpriced() },
			{ status: 200, json: settled() }
		]);

		vi.useFakeTimers();
		try {
			const reading = createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');
			// the wait between asks, which is real time on the deployed runtime and none here.
			await vi.advanceTimersByTimeAsync(2_000);
			const result = await reading;

			expect(result.ok === true && result.value.feeMinor).toBe(330);
			expect(calls).toHaveLength(2);
		} finally {
			vi.useRealTimers();
		}
	});

	/**
	 * an intent still in flight is answered at once, however fresh it is.
	 *
	 * a payment that has not succeeded has no fee because no money has moved, which is an ordinary
	 * absence rather than a figure on its way — and it is the one that must never be held open. a
	 * bank debit sits in `processing` for days, so a delivery about one answered with a refusal would
	 * be redelivered against an intent that answers identically every time until the retry window
	 * runs out, on a gift that has not gone wrong at all.
	 */
	it.each(['processing', 'requires_action'])(
		'answers a fresh %s intent without asking again',
		async (status) => {
			const { httpClient, calls } = recording([
				{ status: 200, json: unpriced(0, { status, latest_charge: null }) }
			]);

			const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

			expect(result.ok === true && result.value.status).toBe('pending');
			expect(calls).toHaveLength(1);
		}
	);

	/**
	 * a fee that has not arrived by the last ask is a refusal, so the delivery comes back.
	 *
	 * the alternative is the defect this exists to close: a settlement reported clean with no fee,
	 * posted at face value under a 200, with nothing that ever looks again. refused, the read is
	 * `fee_not_ready` — retryable in ./provider.ts, which ../donations/settle.ts turns into the 503
	 * the processor redelivers on. nothing is written before this point, so the redelivery finds the
	 * books untouched and posts the charge and its fee in one batch.
	 */
	it('refuses a settlement whose fee has not arrived by the last ask', async () => {
		const { httpClient, calls } = recording([
			{ status: 200, json: unpriced() },
			{ status: 200, json: unpriced() },
			{ status: 200, json: unpriced() }
		]);

		vi.useFakeTimers();
		try {
			const reading = createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');
			await vi.advanceTimersByTimeAsync(2_000 * 2);
			const result = await reading;

			expect(result.ok === false && result.reason).toBe('fee_not_ready');
			expect(calls).toHaveLength(3);
		} finally {
			vi.useRealTimers();
		}
	});

	/**
	 * a fee that never arrived stops being waited for, so the gift is not lost with it.
	 *
	 * Stripe gives up redelivering after about three days, and an account on interchange-plus pricing
	 * cannot read a fee off the balance transaction at all
	 * (https://docs.stripe.com/expand/use-cases) — so a read that refused for as long as the figure
	 * was missing would spend the whole retry window refusing and the charge would never be posted.
	 * past the window the settlement comes back without a fee, which is today's behaviour and what
	 * ../donations/settle.ts alerts on. no second ask either: the answer will not have changed.
	 */
	it('reports a charge hours old with no fee rather than waiting for one', async () => {
		const { httpClient, calls } = recording([{ status: 200, json: unpriced(7 * 60 * 60) }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === true && result.value.feeMinor).toBeNull();
		expect(result.ok === true && result.value.status).toBe('succeeded');
		expect(calls).toHaveLength(1);
	});

	/**
	 * a field that came back as an id is a fault, not an absence.
	 *
	 * an unexpanded field is the request having gone out without its `expand`, which is a bug
	 * here. collapsed onto "there is no charge yet" it reads as a perfectly good settlement with
	 * no processor fee, under a 200, forever — so the ledger records no fee and nothing reports
	 * why.
	 */
	it.each([
		['the charge', { latest_charge: 'ch_1' }],
		[
			'the balance transaction',
			{
				latest_charge: {
					id: 'ch_1',
					object: 'charge',
					amount: 10_329,
					created: 1_770_000_060,
					payment_method_details: { type: 'card' },
					balance_transaction: 'txn_1'
				}
			}
		]
	])('refuses a settlement where %s came back unexpanded', async (_label, overrides) => {
		const { httpClient } = recording([{ status: 200, json: settled(overrides) }]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement('pi_1');

		expect(result.ok === false && result.reason).toBe('provider_error');
	});

	/** an id this account has never held — a delivery replayed from somewhere else reads this way. */
	it('reports a transaction this account does not hold as not_found', async () => {
		const { httpClient } = recording([
			{
				status: 404,
				json: {
					error: {
						type: 'invalid_request_error',
						code: 'resource_missing',
						message: 'No such payment_intent: pi_nope'
					}
				}
			}
		]);

		const result = await createStripeProvider(CREDENTIALS, { httpClient }).readSettlement(
			'pi_nope'
		);

		expect(result.ok === false && result.reason).toBe('not_found');
	});
});

/** the account as `/v1/account` answers it, defaulting to one approved for both rails. */
